package utils;

public class Couleurs {

    public Couleurs()
    {

    }

    public String jaune()
    {
        return "\u001B[33m";
    }

    public String rouge()
    {
        return "\u001B[31m";
    }

    public String vert()
    {
        return "\u001B[32m";
    }

    public String bleu()
    {
        return "\u001B[34m";
    }

    public String cyan()
    {
        return "\u001B[36m";
    }

    public String gris()
    {
        return "\u001B[37m";
    }

    public String reset()
    {
        return "\u001B[0m";
    }

}
